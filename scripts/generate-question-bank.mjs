import {mkdir,writeFile} from 'node:fs/promises'
import {topic1} from './question-bank/topic1.mjs'
import {topic2} from './question-bank/topic2.mjs'
import {topic3} from './question-bank/topic3.mjs'
import {topic4} from './question-bank/topic4.mjs'
import {topic5} from './question-bank/topic5.mjs'
import {extras} from './question-bank/extras.mjs'
import {compilePoint} from './question-bank/helpers.mjs'

const pointSets={...topic1,...topic2,...topic3,...topic4,...topic5}
const codes=Object.keys(pointSets)
if(codes.length!==83)throw new Error(`Expected 83 syllabus points, found ${codes.length}`)

const slug=value=>value.toLowerCase().replace(/[^a-z0-9]+/g,'-').replace(/^-|-$/g,'')
const questions=codes.flatMap(code=>[
  ...compilePoint(code,pointSets[code]).map((question,index)=>({...question,seedId:`aa-${slug(code)}-${['recall','concept','misconception'][index]??`math-${index+1}`}`})),
  ...compilePoint(code,extras[code]??[],false).map((question,index)=>({...question,seedId:`aa-${slug(code)}-extra-${index+1}`})),
])

const output={format:'math_quiz_import_v1.1',courseFamily:'analysis_approaches',courseLevel:'HL',course:'IB Mathematics: Analysis and Approaches HL',source:'platform_seed',generatedBy:'scripts/generate-question-bank.mjs',questions}
await mkdir(new URL('../src/data/',import.meta.url),{recursive:true})
await writeFile(new URL('../src/data/aaQuestionSeed.generated.json',import.meta.url),`${JSON.stringify(output,null,2)}\n`)

const questionUuid=index=>`50000000-0000-0000-0000-${String(index+1).padStart(12,'0')}`
const answerData=question=>{
  if(question.type==='multiple_choice'||question.type==='true_false'||question.type==='numeric_answer')return {answer:question.answer,...(question.tolerance===undefined?{}:{tolerance:question.tolerance})}
  if(question.type==='short_answer'||question.type==='fill_blank')return {answer:question.answer,acceptedAnswers:question.acceptedAnswers??[]}
  if(question.type==='multi_select')return {answers:question.answers}
  if(question.type==='matching')return {pairs:question.pairs}
  if(question.type==='ordering')return {items:question.items,correctOrder:question.correctOrder}
  return {zones:question.zones,items:question.items}
}
const choicesFor=question=>{
  const choices=question.type==='true_false'?['True','False']:question.choices
  const correct=question.type==='true_false'?[question.answer?'True':'False']:question.type==='multi_select'?question.answers:[question.answer]
  return {choices:choices??[],correctChoices:correct.filter(value=>value!==undefined)}
}

const sqlPayload=questions.map((question,index)=>{
  const {choices,correctChoices}=choicesFor(question)
  return {seed_id:questionUuid(index),is_core:!question.seedId.includes('-extra-'),syllabus_code:question.syllabusCode,type:question.type,prompt:question.prompt,answer_data:answerData(question),explanation:question.explanation,difficulty:question.difficulty,question_style:question.questionStyle,calculator:question.calculator,estimated_time_seconds:question.estimatedTimeSeconds,marks_estimate:question.marksEstimate,tags:question.tags,choices,correct_choices:correctChoices}
})
