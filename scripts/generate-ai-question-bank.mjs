import {mkdir,readFile,writeFile} from 'node:fs/promises'
import {aiTopic1} from './question-bank-ai/topic1.mjs'
import {aiTopic2} from './question-bank-ai/topic2.mjs'
import {aiTopic3} from './question-bank-ai/topic3.mjs'
import {aiTopic4} from './question-bank-ai/topic4.mjs'
import {aiTopic5} from './question-bank-ai/topic5.mjs'
import {compilePoint} from './question-bank/helpers.mjs'

const pointSets={...aiTopic1,...aiTopic2,...aiTopic3,...aiTopic4,...aiTopic5}
const codes=Object.keys(pointSets)
if(codes.length!==78)throw new Error(`Expected 78 AI syllabus points, found ${codes.length}`)

const slug=value=>value.toLowerCase().replace(/[^a-z0-9]+/g,'-').replace(/^-|-$/g,'')
const questions=codes.flatMap(code=>compilePoint(code,pointSets[code]).map((question,index)=>({
  ...question,
  seedId:`ai-${slug(code)}-${['recall','procedure','concept'][index]}`,
  courseFamily:'applications_interpretation',
  courseLevel:code.startsWith('AHL')?'HL':'SL',
})))

const output={
  format:'math_quiz_import_v1.1',
  courseFamily:'applications_interpretation',
  courseLevel:'HL',
  course:'IB Mathematics: Applications and Interpretation HL',
  source:'platform_seed',
  generatedBy:'scripts/generate-ai-question-bank.mjs',
  questions,
}
await mkdir(new URL('../src/data/',import.meta.url),{recursive:true})
await writeFile(new URL('../src/data/aiQuestionSeed.generated.json',import.meta.url),`${JSON.stringify(output,null,2)}\n`)

const syllabusSource=await readFile(new URL('../src/data/aiSyllabus.ts',import.meta.url),'utf8')
const syllabusRows=[...syllabusSource.matchAll(/\['((?:SL|AHL)\s+[1-5]\.\d+)','([^']+)','([^']+)'\]/g)].map(match=>({
  code:match[1],
  title:match[2],
  description:match[3],
  topic_number:Number(match[1].match(/[1-5]/)?.[0]??1),
  level:match[1].startsWith('AHL')?'AHL':'SL',
}))
if(syllabusRows.length!==78)throw new Error(`Expected 78 parsed AI syllabus rows, found ${syllabusRows.length}`)

const questionUuid=index=>`51000000-0000-0000-0000-${String(index+1).padStart(12,'0')}`
const answerData=question=>{
  if(question.type==='multiple_choice'||question.type==='true_false'||question.type==='numeric_answer')return {answer:question.answer,...(question.tolerance===undefined?{}:{tolerance:question.tolerance})}
  if(question.type==='short_answer'||question.type==='fill_blank')return {answer:question.answer,acceptedAnswers:question.acceptedAnswers??[]}
  if(question.type==='multi_select')return {answers:question.answers}
  if(question.type==='matching')return {pairs:question.pairs}
  if(question.type==='ordering')return {items:question.items,correctOrder:question.correctOrder}
  return {zones:question.zones,items:question.items}
}
const choicesFor=question=>{
  const choices=question.type==='true_false'?['True','False']:question.choices
  const correct=question.type==='true_false'?[question.answer?'True':'False']:question.type==='multi_select'?question.answers:[question.answer]
  return {choices:choices??[],correctChoices:(correct??[]).filter(value=>value!==undefined)}
}
const questionRows=questions.map((question,index)=>{
  const {choices,correctChoices}=choicesFor(question)
  return {
    seed_id:questionUuid(index),
    syllabus_code:question.syllabusCode,
    type:question.type,
    prompt:question.prompt,
    answer_data:answerData(question),
    explanation:question.explanation,
    difficulty:question.difficulty,
    question_style:question.questionStyle,
    calculator:question.calculator,
    estimated_time_seconds:question.estimatedTimeSeconds,
    marks_estimate:question.marksEstimate,
    tags:question.tags,
    choices,
    correct_choices:correctChoices,
  }
})

